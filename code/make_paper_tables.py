"""Regenerate numerical result tables from algorithm outputs, not published tables.

Writes transient .tex/.csv files to paper/tables/ (Git-ignored). The paper's
printed tables, captions and expected number rows are NOT read as inputs.
BMC Tables 1--4 are separately generated by code/reproduce_bmc.py.
"""
from pathlib import Path
import hashlib, json, subprocess, sys
ROOT=Path(__file__).resolve().parents[1]
TABLES=ROOT/"paper/tables"
OUT=ROOT/"code/out"

def main():
    TABLES.mkdir(parents=True,exist_ok=True)
    for f in TABLES.glob("Table*.tex"):f.unlink()
    for script in ("make_tables.py","make_supp_tables.py","make_block_diagnostics.py",
                   "make_case_study.py","make_table_s9.py","_table_builder.py"):
        subprocess.run([sys.executable,str(ROOT/"code"/script)],cwd=ROOT,check=True)
    paths=sorted(TABLES.glob("Table*.tex"))
    if len(paths)<13:raise RuntimeError(f"Expected >=13 calculated numeric tables; got {len(paths)}")
    manifest={}
    for p in paths:
        b=p.read_bytes()
        if len(b)<120 or b"\\begin{tabular}" not in b or b"\\end{tabular}" not in b:
            raise ValueError(f"Incomplete generated table: {p}")
        manifest[p.name]={"sha256":hashlib.sha256(b).hexdigest(),"bytes":len(b)}
    OUT.mkdir(parents=True,exist_ok=True)
    (OUT/"table_generation.json").write_text(json.dumps(manifest,indent=2)+"\n")
    print(f"PASS: generated {len(paths)} numeric tables from analysis outputs; no publication table read")

if __name__=="__main__":main()
